#!/bin/sh
# Builds the Android app (APK). First time: downloads the Android SDK/NDK (~3 GB) and takes 30-60 minutes.
# After that it's a few minutes. Needs ~/.local/share/android-build (Java 17 + a Python 3.11 venv with buildozer).
# The APK ends up in android/bin/.  Put it on the phone:  kdeconnect-cli -n "Pixel 10a" --share android/bin/*.apk
set -e
cd "$(dirname "$0")"
B="$HOME/.local/share/android-build"
export JAVA_HOME="$(ls -d "$B"/jdk-17* | head -1)"
export PKG_CONFIG_PATH="/usr/lib/openssl-3/pkgconfig${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}"   # (Python needs OpenSSL 3; the system default is 4)
export P4A_pygame_DIR="$B/pygame-2.6.1"   # pygame 2.6.1 with its C code regenerated by Cython 3.1 (the recipe's 2.1.0 is too old for Python 3.14)
export VIRTUAL_ENV="$B/venv"
export PATH="$JAVA_HOME/bin:$B/venv/bin:$B/bin:$PATH"
rm -rf app && mkdir -p app/fonts
cp ../game/*.py main.py app/
rm -f app/showcase.py
cp -r ../game/sounds ../game/assets app/
/usr/bin/python3 - <<'PY'                                # the fonts the game uses, copied in (Android has none of them)
import os, shutil, sys
sys.path.insert(0, "../game")
import fonts
for f in fonts.ALL:
    if os.path.exists(f):
        shutil.copy(f, "app/fonts/")
PY
/usr/bin/python3 make_icon.py app/icon.png
buildozer android debug
ls -la bin/*.apk
