class Painter:
    """Draws tiles into a numpy RGB image."""

    def __init__(self, w, h):
        self.img = np.zeros((h * T, w * T, 3), np.uint8)
        self.img[:] = P["void"]

    def cell(self, x, y):
        return self.img[y * T:(y + 1) * T, x * T:(x + 1) * T]

    def fill(self, x, y, col):
        self.cell(x, y)[:] = col

    def bitmap(self, x, y, b, cols, dx=0, dy=0):
        c = self.cell(x, y)
        for k, col in zip("123", cols):
            if col is None:
                continue
            m = b == k
            if dx or dy:
                m = np.roll(np.roll(m, dy, 0), dx, 1)
            c[m] = col

    def stamp(self, x, y, st, cols, px, py):
        c = self.cell(x, y)
        h, w = st.shape
        for k, col in zip("123", cols):
            ys, xs = np.nonzero(st == k)
            ys, xs = ys + py, xs + px
            ok = (ys >= 0) & (ys < T) & (xs >= 0) & (xs < T)
            c[ys[ok], xs[ok]] = col

    def line(self, x0, y0, x1, y1, col, w=3):
        """thick line in image pixel coords (for rivers/roads)"""
        n = int(max(abs(x1 - x0), abs(y1 - y0))) + 1
        H, W = self.img.shape[:2]
        for i in range(n + 1):
            t = i / n
            cx, cy = x0 + (x1 - x0) * t, y0 + (y1 - y0) * t
            a, b = int(cy - w / 2), int(cx - w / 2)
            self.img[max(0, a):min(H, a + w), max(0, b):min(W, b + w)] = col
